// Downloads the fonts offered by the document designer (OFL, via Fontsource) into public/fonts/doc
// and writes src/lib/doc/bundled-fonts.ts. Run: node scripts/fetch-doc-fonts.mjs
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "public", "fonts", "doc");
const outTs = path.join(root, "src", "lib", "doc", "bundled-fonts.ts");

const FONTS = [
  { id: "amiri", category: "arabic", fallback: "serif" },
  { id: "noto-naskh-arabic", category: "arabic", fallback: "serif" },
  { id: "scheherazade-new", category: "arabic", fallback: "serif" },
  { id: "cairo", category: "arabic", fallback: "sans-serif" },
  { id: "tajawal", category: "arabic", fallback: "sans-serif" },
  { id: "almarai", category: "arabic", fallback: "sans-serif" },
  { id: "ibm-plex-sans-arabic", category: "arabic", fallback: "sans-serif" },
  { id: "noto-kufi-arabic", category: "arabic", fallback: "sans-serif" },
  { id: "roboto", category: "latin", fallback: "sans-serif" },
  { id: "open-sans", category: "latin", fallback: "sans-serif" },
  { id: "lato", category: "latin", fallback: "sans-serif" },
  { id: "montserrat", category: "latin", fallback: "sans-serif" },
  { id: "poppins", category: "latin", fallback: "sans-serif" },
  { id: "merriweather", category: "latin", fallback: "serif" },
  { id: "lora", category: "latin", fallback: "serif" },
  { id: "playfair-display", category: "latin", fallback: "serif" },
];
const WEIGHTS = [400, 700];

async function json(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.json();
}

function closest(weights, wanted) {
  return [...weights].sort((a, b) => Math.abs(a - wanted) - Math.abs(b - wanted))[0];
}

await mkdir(outDir, { recursive: true });
const out = [];
for (const font of FONTS) {
  const meta = await json(`https://api.fontsource.org/v1/fonts/${font.id}`);
  const subsets = (font.category === "arabic" ? ["arabic", "latin"] : ["latin"]).filter((s) => meta.subsets.includes(s));
  const faces = [];
  for (const wanted of WEIGHTS) {
    const weight = closest(meta.weights, wanted);
    for (const subset of subsets) {
      const file = `${font.id}-${subset}-${weight}.woff2`;
      const res = await fetch(`https://cdn.jsdelivr.net/fontsource/fonts/${font.id}@latest/${subset}-${weight}-normal.woff2`);
      if (!res.ok) throw new Error(`${file}: ${res.status}`);
      await writeFile(path.join(outDir, file), Buffer.from(await res.arrayBuffer()));
      faces.push({ weight: wanted, file: `/fonts/doc/${file}`, range: meta.unicodeRange[subset].replace(/,/g, ", ") });
    }
  }
  out.push({ family: meta.family, category: font.category, fallback: font.fallback, faces });
  console.log(`${meta.family}: ${faces.length} files`);
}

const ts = `// Generated by scripts/fetch-doc-fonts.mjs — do not edit by hand.

export type BundledFontFace = { weight: number; file: string; range: string };
export type BundledFont = { family: string; category: "arabic" | "latin"; fallback: string; faces: BundledFontFace[] };

export const BUNDLED_FONTS: BundledFont[] = ${JSON.stringify(out, null, 2)};
`;
await writeFile(outTs, ts);
console.log(`wrote ${path.relative(root, outTs)}`);
